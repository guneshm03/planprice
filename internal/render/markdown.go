package render

import (
	"fmt"
	"io"
	"strings"

	"github.com/guneshm03/planprice/internal/estimate"
)

// mdEscape escapes characters that would break a Markdown table cell.
func mdEscape(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}

func code(s string) string { return "`" + strings.ReplaceAll(s, "`", "'") + "`" }

func breakdownMarkdown(w io.Writer, est *estimate.Estimate) error {
	var b strings.Builder
	fmt.Fprintf(&b, "### planprice: estimated monthly cost **%s**\n\n", usd(est.Monthly))
	fmt.Fprintf(&b, "Plan: %s\n\n", code(est.Label))
	b.WriteString("| Resource | Region | Monthly cost |\n|---|---|---:|\n")
	for _, r := range est.Resources {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code(r.Address), r.Region, usd(r.Monthly))
	}
	fmt.Fprintf(&b, "| **Total** | | **%s** |\n\n", usd(est.Monthly))
	writeComponentDetails(&b, est)
	writeMarkdownNotes(&b, est)
	_, err := io.WriteString(w, b.String())
	return err
}

func writeComponentDetails(b *strings.Builder, est *estimate.Estimate) {
	b.WriteString("<details><summary>Cost components</summary>\n\n")
	b.WriteString("| Resource | Component | Quantity | Unit price | Monthly |\n|---|---|---:|---:|---:|\n")
	for _, r := range est.Resources {
		row := func(name string, c estimate.ComponentCost) {
			qty, rate, cost := componentCells(c)
			if qty != "-" {
				qty += " " + c.Unit
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", code(r.Address), mdEscape(name), qty, rate, cost)
		}
		for _, c := range r.Components {
			row(c.Name, c)
		}
		for _, g := range r.Groups {
			for _, c := range g.Components {
				row(g.Name+" / "+c.Name, c)
			}
		}
	}
	b.WriteString("\n\\* tiered price; the blended rate for the quantity is shown.\n\n</details>\n\n")
}

func writeMarkdownNotes(b *strings.Builder, est *estimate.Estimate) {
	if m := missingUsage(est); len(m) > 0 {
		fmt.Fprintf(b, "<details><summary>%s excluded until usage is supplied</summary>\n\n",
			plural(len(m), "usage-based component", "usage-based components"))
		for _, line := range m {
			fmt.Fprintf(b, "- %s\n", mdEscape(line))
		}
		b.WriteString("\nGenerate a usage file with `planprice usage-template --plan <plan.json>`.\n\n</details>\n\n")
	}
	if u := unpriced(est); len(u) > 0 {
		b.WriteString("**Not priced:**\n\n")
		for _, line := range u {
			fmt.Fprintf(b, "- %s\n", mdEscape(line))
		}
		b.WriteString("\n")
	}
	if sk := skippedByType(est); len(sk) > 0 {
		fmt.Fprintf(b, "**Unsupported resource types (not included):** %s\n\n", strings.Join(sk, ", "))
	}
	for _, warn := range est.Warnings {
		fmt.Fprintf(b, "> **Warning:** %s\n\n", mdEscape(warn))
	}
	fmt.Fprintf(b, "<sub>%s Generated by planprice.</sub>\n", footer(est))
}

func diffMarkdown(w io.Writer, d *estimate.Diff) error {
	var b strings.Builder
	b.WriteString(CommentMarker + "\n")
	switch d.Delta.Sign() {
	case 1:
		fmt.Fprintf(&b, "### planprice: monthly cost will increase by **%s** (%s)\n\n", signed(d.Delta), percent(d.Percent))
	case -1:
		fmt.Fprintf(&b, "### planprice: monthly cost will decrease by **%s** (%s)\n\n", usd(d.Delta.Neg()), percent(d.Percent))
	default:
		b.WriteString("### planprice: no change in monthly cost\n\n")
	}
	b.WriteString("| | Monthly cost |\n|---|---:|\n")
	fmt.Fprintf(&b, "| Base %s | %s |\n", code(d.Base.Label), usd(d.BaseTotal))
	fmt.Fprintf(&b, "| Head %s | %s |\n", code(d.Head.Label), usd(d.HeadTotal))
	fmt.Fprintf(&b, "| **Change** | **%s (%s)** |\n\n", signed(d.Delta), percent(d.Percent))

	var changed []estimate.ResourceDiff
	for _, r := range d.Resources {
		if r.Kind != estimate.Unchanged {
			changed = append(changed, r)
		}
	}
	if len(changed) > 0 {
		b.WriteString("| Resource | Change | Base | Head | Diff |\n|---|---|---:|---:|---:|\n")
		for _, r := range changed {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", code(r.Address), r.Kind, usdOrDash(r, true), usdOrDash(r, false), signed(r.Delta))
		}
		b.WriteString("\n<details><summary>Component changes</summary>\n\n")
		b.WriteString("| Resource | Component | Base | Head | Diff |\n|---|---|---:|---:|---:|\n")
		for _, r := range changed {
			for _, c := range r.Components {
				if !c.Significant() {
					continue
				}
				fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", code(r.Address), mdEscape(componentLabel(c)), usd(c.Base), usd(c.Head), signed(c.Delta))
			}
		}
		b.WriteString("\n</details>\n\n")
	}
	writeComponentDetails(&b, d.Head)
	writeMarkdownNotes(&b, d.Head)
	_, err := io.WriteString(w, b.String())
	return err
}
