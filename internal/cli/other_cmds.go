func runUsageTemplate(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("usage-template", stderr)
	planPath := fs.String("plan", "", "plan JSON (required)")
	out := fs.String("out", "", "write the template to this file instead of stdout")
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	if err := requireFlag("plan", *planPath); err != nil {
		return err
	}
	plan, err := tfplan.ParseFile(*planPath)
	if err != nil {
		return err
	}
	resources, err := plan.Resources(tfplan.After, "us-east-1", nil)
	if err != nil {
		return err
	}
	entries := make([]usage.TemplateEntry, 0, len(resources))
	for _, r := range resources {
		entries = append(entries, usage.TemplateEntry{Address: r.Address, Type: r.Type})
	}
	w, closeFn, err := output(*out, stdout)
	if err != nil {
		return err
	}
	reg := mapper.NewRegistry()
	if _, err := io.WriteString(w, usage.Template(entries, reg.UsageSchema)); err != nil {
		_ = closeFn()
		return err
	}
	return closeFn()
}

func runResources(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("resources", stderr)
	format := fs.String("format", "table", "table or markdown")
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	reg := mapper.NewRegistry()
	switch *format {
	case "markdown":
		_, err := io.WriteString(stdout, ResourcesMarkdown(reg))
		return err
	case "table":
		var b strings.Builder
		for _, t := range reg.Types() {
			m, _ := reg.Lookup(t)
			d := m.Doc()
			keys := make([]string, 0)
			for _, f := range m.UsageSchema() {
				keys = append(keys, f.Key)
			}
			fmt.Fprintf(&b, "%-22s %-24s %s\n", t, d.Service, d.Summary)
			if len(keys) > 0 {
				fmt.Fprintf(&b, "%-22s usage keys: %s\n", "", strings.Join(keys, ", "))
			}
		}
		fmt.Fprintf(&b, "\n%d resource types are known to be free (e.g. %s).\n", len(mapper.FreeTypes()), strings.Join(mapper.FreeTypes()[:3], ", "))
		_, err := io.WriteString(stdout, b.String())
		return err
	default:
		return fmt.Errorf("%w: --format must be table or markdown", errUsage)
	}
}

// ResourcesMarkdown renders the supported-resource reference. The committed
// docs/RESOURCES.md is this output; a test keeps them in sync.
func ResourcesMarkdown(reg *mapper.Registry) string {
	var b strings.Builder
	b.WriteString("# Supported resources\n\n")
	b.WriteString("<!-- Generated by `planprice resources --format markdown`; do not edit by hand. -->\n\n")
	b.WriteString("All prices are on-demand list prices from the embedded AWS price snapshot. ")
	b.WriteString("A month is 730 hours. Components marked *usage-based* are excluded from totals until a usage file supplies them.\n\n")
	for _, t := range reg.Types() {
		m, _ := reg.Lookup(t)
		d := m.Doc()
		fmt.Fprintf(&b, "## `%s` (%s)\n\n%s\n\n**Priced:**\n\n", t, d.Service, d.Summary)
		for _, p := range d.Priced {
			fmt.Fprintf(&b, "- %s\n", p)
		}
		if fields := m.UsageSchema(); len(fields) > 0 {
			b.WriteString("\n**Usage keys:**\n\n| Key | Description |\n|---|---|\n")
			writeFieldRows(&b, fields, "")
		}
		b.WriteString("\n**Assumptions and exclusions:**\n\n")
		for _, a := range d.Assumptions {
			fmt.Fprintf(&b, "- %s\n", a)
		}
		b.WriteString("\n")
	}
	b.WriteString("## Free resource types\n\nThese are reported as free rather than unsupported:\n\n")
	for _, t := range mapper.FreeTypes() {
		fmt.Fprintf(&b, "- `%s`\n", t)
	}
	return b.String()
}

func writeFieldRows(b *strings.Builder, fields []usage.Field, prefix string) {
	for _, f := range fields {
		desc := f.Description
		if f.Kind == usage.Enum || f.Kind == usage.GroupMap {
			desc += " (one of: " + strings.Join(f.Enum, ", ") + ")"
		}
		fmt.Fprintf(b, "| `%s%s` | %s |\n", prefix, f.Key, desc)
		if f.Kind == usage.GroupMap {
			writeFieldRows(b, f.Fields, prefix+f.Key+".<class>.")
		}
	}
}

func runSnapshot(args []string, stdout, stderr io.Writer) error {
	if len(args) == 0 {
		return fmt.Errorf("%w: snapshot needs a subcommand: info, verify, lookup or diff", errUsage)
	}
	switch args[0] {
	case "info":
		fs := newFlagSet("snapshot info", stderr)
		path := fs.String("snapshot", "", "snapshot file (default: embedded)")
		if err := parseFlags(fs, args[1:]); err != nil {
			return err
		}
		snap, err := loadSnapshot(*path)
		if err != nil {
			return err
		}
		var b strings.Builder
		fmt.Fprintf(&b, "Source:     %s\nGenerated:  %s\nCurrency:   %s\nPrices:     %d\nRegions:    %s\n\n",
			snap.Source, snap.GeneratedAt, snap.Currency, len(snap.Prices), strings.Join(snap.Regions(), ", "))
		fmt.Fprintf(&b, "%-10s %-10s %-16s %-22s %s\n", "SERVICE", "REGION", "OFFER VERSION", "PUBLISHED", "PRICES")
		for _, o := range snap.Offers {
			fmt.Fprintf(&b, "%-10s %-10s %-16s %-22s %d\n", o.Service, o.Region, o.Version, o.PublicationDate, o.Products)
		}
		_, err = io.WriteString(stdout, b.String())
		return err
	case "verify":
		if err := parseFlags(newFlagSet("snapshot verify", stderr), args[1:]); err != nil {
			return err
		}
		sum, err := pricedata.VerifyEmbedded()
		if err != nil {
			return err
		}
		if _, err := pricedata.Default(); err != nil {
			return err
		}
		_, err = fmt.Fprintf(stdout, "embedded snapshot OK (sha256 %s)\n", sum)
		return err
	case "lookup":
		return runSnapshotLookup(args[1:], stdout, stderr)
	case "diff":
		fs := newFlagSet("snapshot diff", stderr)
		if err := fs.Parse(args[1:]); err != nil {
			return fmt.Errorf("%w: %w", errUsage, err)
		}
		if fs.NArg() != 2 {
			return fmt.Errorf("%w: snapshot diff OLD NEW (use \"embedded\" for the built-in snapshot)", errUsage)
		}
		oldSnap, err := loadSnapshot(fs.Arg(0))
		if err != nil {
			return err
		}
		newSnap, err := loadSnapshot(fs.Arg(1))
		if err != nil {
			return err
		}
		return writeSnapshotDiff(stdout, pricing.DiffSnapshots(oldSnap, newSnap))
	default:
		return fmt.Errorf("%w: unknown snapshot subcommand %q", errUsage, args[0])
	}
}

func writeSnapshotDiff(w io.Writer, changes []pricing.PriceChange) error {
	var b strings.Builder
	counts := map[string]int{}
	for _, c := range changes {
		counts[c.Kind()]++
		oldS, newS := "-", "-"
		if c.Old != nil {
			oldS = money.FormatUnitPrice(*c.Old)
		}
		if c.New != nil {
			newS = money.FormatUnitPrice(*c.New)
		}
		fmt.Fprintf(&b, "%-8s %s  %s -> %s per %s\n", c.Kind(), c.Identity, oldS, newS, c.Unit)
	}
	fmt.Fprintf(&b, "%d added, %d removed, %d changed\n", counts["added"], counts["removed"], counts["changed"])
	_, err := io.WriteString(w, b.String())
	return err
}

type attrFlags []string

func (a *attrFlags) String() string     { return strings.Join(*a, ",") }
func (a *attrFlags) Set(v string) error { *a = append(*a, v); return nil }

func runSnapshotLookup(args []string, stdout, stderr io.Writer) error {
	fs := newFlagSet("snapshot lookup", stderr)
	path := fs.String("snapshot", "", "snapshot file (default: embedded)")
	service := fs.String("service", "", "offer code, e.g. AmazonEC2 (required)")
	region := fs.String("region", "us-east-1", "region")
	family := fs.String("family", "", "product family, e.g. \"Compute Instance\" (required)")
	qty := fs.String("quantity", "", "optional quantity to price through the tiers")
	var attrs attrFlags
	fs.Var(&attrs, "attr", "attribute filter key=value (repeatable)")
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	if err := requireFlag("service", *service); err != nil {
		return err
	}
	if err := requireFlag("family", *family); err != nil {
		return err
	}
	q := pricing.Query{Service: *service, Region: *region, Family: *family, Attrs: map[string]string{}}
	for _, a := range attrs {
		k, v, ok := strings.Cut(a, "=")
		if !ok {
			return fmt.Errorf("%w: --attr must be key=value, got %q", errUsage, a)
		}
		q.Attrs[k] = v
	}
	snap, err := loadSnapshot(*path)
	if err != nil {
		return err
	}
	p, err := snap.Lookup(q)
	if err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s\nsku %s, unit %s\n", p.Identity(), p.SKU, p.Unit)
	for _, t := range p.Tiers {
		end := "Inf"
		if t.End != nil {
			end = t.End.String()
		}
		fmt.Fprintf(&b, "  [%s, %s): %s\n", t.Start, end, money.FormatUnitPrice(t.USD))
	}
	if *qty != "" {
		d, err := money.Parse(*qty)
		if err != nil {
			return fmt.Errorf("%w: --quantity: %w", errUsage, err)
		}
		fmt.Fprintf(&b, "cost of %s %s: %s\n", d, p.Unit, money.FormatUSD(p.Cost(d), 4))
	}
	_, err = io.WriteString(stdout, b.String())
	return err
}
